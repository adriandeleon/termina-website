// Checks the command ids and the keys quoted in the user guide and the feature pages against the
// generated command data in src/lib/commands.ts, so a key that moves in the app, or an id that
// never existed, fails here and does not go stale on the site (DOCS-04, Pauta 6.0.1).
// Run with `npm run check:docs`; exits non-zero on an error. Ported from editora-website's, whose
// pages pair a key with a command's id; these pair it with the command's title.
//
// What it checks, in src/content/docs/*.md and src/content/features/*.md:
//   1. A backticked token that looks like a command id (`<area>.<name>`, where <area> is one the
//      commands use) names a real command. So does the id after `keys.` in a settings key.
//   2. In a table row whose first cell holds keys and whose second cell opens with a command's
//      title ("| `Ctrl+Shift+T` (`Cmd+T`) | New Tab, running the default profile |"), no key in
//      the first cell is the default of a different command, on the system the key is written for.
// A key that is no command's default (Ctrl+Insert, which the terminal handles itself) is a note.
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const src = readFileSync(join(root, "src/lib/commands.ts"), "utf8");

const commands = []; // { id, title, pc, mac }
// A chord is an array of quoted keys, and a key may be "]" itself.
const keysOf = String.raw`(null|\[(?:"(?:[^"\\]|\\.)*"(?:, )?)*\])`;
const row = new RegExp(
  String.raw`\{ id: "([^"]+)", title: "((?:[^"\\]|\\.)*)", desc: "(?:[^"\\]|\\.)*", pc: ${keysOf}, mac: ${keysOf} \}`,
  "g",
);
for (const m of src.matchAll(row)) {
  const keys = (s) => (s === "null" ? null : JSON.parse(s));
  commands.push({ id: m[1], title: m[2].replace(/\\"/g, '"'), pc: keys(m[3]), mac: keys(m[4]) });
}
if (commands.length < 40) {
  console.error(`check-doc-commands: parsed only ${commands.length} commands from commands.ts`);
  process.exit(2);
}
const ids = new Set(commands.map((c) => c.id));
const areas = new Set(commands.map((c) => c.id.split(".")[0]));

// A chord as a comparable string: its modifiers sorted, then its key, lower case.
const norm = (keys) => {
  const k = keys.map((s) => s.trim()).filter(Boolean);
  const key = k.pop();
  return [...k.map((s) => s.toLowerCase()).sort(), key.toLowerCase()].join("+");
};
const ownerPc = new Map();
const ownerMac = new Map();
for (const c of commands) {
  if (c.pc) ownerPc.set(norm(c.pc), c);
  if (c.mac) ownerMac.set(norm(c.mac), c);
}
// Titles, longest first, so "New Tab With Profile 1" is tried before "New Tab".
const plain = (t) => t.replace(/…$/, "").toLowerCase();
const byTitle = [...commands].sort((a, b) => b.title.length - a.title.length);

const FILE_EXT = /\.(json|md|xml|yml|yaml|toml|properties|java|ts|js|mjs|css|html|txt|log|sh|py|png|svg|jar|exe|app|deb|rpm|dmg|msi|asc|gz|terminal|itermcolors|conf|bashrc|zshrc|profile)$/i;
// Dotted names that share an area with commands and are not commands: the keys of settings.json.
const NOT_COMMANDS = new Set([
  "sync.repository",
  "sync.branch",
  "sync.auto",
  "sync.intervalMinutes",
  "sync.enabled",
  "sync.folder",
]);
const ID_SHAPE = /^[a-z][A-Za-z]*(\.[A-Za-z][A-Za-z0-9]*)+$/;
const KEY_SHAPE = /^(?:(?:Ctrl|Alt|Shift|Cmd|Option|Meta)\+)+\S+$/;

const errors = [];
const notes = [];
for (const dir of ["src/content/docs", "src/content/features"]) {
  for (const file of readdirSync(join(root, dir)).filter((f) => f.endsWith(".md")).sort()) {
    const rel = `${dir}/${file}`;
    const text = readFileSync(join(root, rel), "utf8");
    // The generated pages quote the app's own files; they are checked where they are made.
    if (text.includes("AUTO-GENERATED by scripts/")) continue;
    const lines = text.split("\n");
    let fenced = false;
    lines.forEach((line, i) => {
      if (/^\s*(```|~~~)/.test(line)) fenced = !fenced;
      if (fenced) return;
      const at = `${rel}:${i + 1}`;
      const ticks = [...line.matchAll(/`([^`]+)`/g)].map((m) => m[1]);
      for (const t of ticks) {
        const id = t.startsWith("keys.") ? t.slice("keys.".length) : t;
        if (!ID_SHAPE.test(id) || FILE_EXT.test(id) || NOT_COMMANDS.has(id)) continue;
        if (!t.startsWith("keys.") && !areas.has(id.split(".")[0])) continue;
        if (!ids.has(id)) errors.push(`${at}  unknown command id \`${id}\``);
      }

      // A table row: keys, then what they do.
      if (!line.trimStart().startsWith("|")) return;
      const cells = line.split("|").map((c) => c.trim());
      const keyCell = cells[1] ?? "";
      const what = (cells[2] ?? "").toLowerCase();
      const named = byTitle.find((c) => {
        const t = plain(c.title);
        return what === t || (what.startsWith(t) && /[\s,.:;(]/.test(what[t.length]));
      });
      if (!named) return;
      const found = [...keyCell.matchAll(/`([^`]+)`/g)]
        .map((m) => m[1])
        .filter((k) => KEY_SHAPE.test(k))
        .map((key) => {
          const mac = /\b(Cmd|Option)\b/.test(key);
          return { key, owner: (mac ? ownerMac : ownerPc).get(norm(key.split("+"))) };
        });
      // A row may cover a pair or a run of commands ("Copy / paste", "Profile 1 to 9") with all
      // their keys: once the named command's own key is among them, the others are its partners'.
      if (found.some((f) => f.owner?.id === named.id)) return;
      for (const { key, owner } of found) {
        if (!owner) {
          notes.push(`${at}  \`${key}\` beside "${named.title}" is no command's default key`);
        } else {
          errors.push(`${at}  \`${key}\` is listed for "${named.title}" but is "${owner.title}" (\`${owner.id}\`) in the app`);
        }
      }
    });
  }
}

for (const n of notes) console.log(`note   ${n}`);
for (const e of errors) console.log(`error  ${e}`);
console.log(`check-doc-commands: ${commands.length} commands, ${errors.length} error(s), ${notes.length} note(s)`);
process.exit(errors.length ? 1 : 0);
