// Generates the user guide's What's New page from the Termina repository's CHANGELOG.md, its
// Roadmap page from TODO.md, and the home page's "What's new" block (src/lib/whatsnew.ts) from the
// newest release's entries (DOCS-04, Pauta 6.0.1). The output is committed, so the site builds
// without the app checked out.
//
//   java scripts/GenChangelog.java [/path/to/Termina] [--ref=v0.15.0] [--as=0.15.0]
//
// The checkout, the ref and --as are GenCommands.java's: the argument, else $TERMINA_REPO, else
// ../Termina; the newest vX.Y.Z tag unless --ref says otherwise; and --as to make the site ready
// ahead of a release, which reads the changelog's [Unreleased] section as that version's.
// Without --as, an [Unreleased] section is what the home page lists under "In development" and
// the What's New page leaves out.
// A JDK 25 compact source file (JEP 512): no build step, nothing outside java.base.

static final String REPO_URL = "https://github.com/adriandeleon/Termina";

record Release(String version, String date, String body) {}

record News(String title, String detail) {}

void main(String[] args) throws IOException, InterruptedException {
    String ref = null;
    String as = null;
    String path = null;
    for (String a : args) {
        if (a.startsWith("--ref=")) ref = a.substring("--ref=".length());
        else if (a.startsWith("--as=")) as = a.substring("--as=".length());
        else path = a;
    }
    Path repo = Path.of(path != null ? path : Objects.requireNonNullElse(System.getenv("TERMINA_REPO"), "../Termina"))
            .toAbsolutePath()
            .normalize();
    if (!Files.exists(repo.resolve(".git"))) {
        System.err.println("No Termina checkout at " + repo + " (pass its path, or set TERMINA_REPO)");
        System.exit(2);
    }
    if (ref == null) ref = newestTag(repo);
    // Links into the repository point at the files as they were at this ref.
    String blob = REPO_URL + "/blob/" + (ref.matches("v\\d+\\.\\d+\\.\\d+") ? ref : "master") + "/";

    List<Release> sections = sections(show(repo, ref, "CHANGELOG.md"));
    Release unreleased = sections.stream().filter(r -> r.version().equals("Unreleased")).findFirst().orElse(null);
    List<Release> released = new ArrayList<>();
    if (as != null && unreleased != null) released.add(new Release(as, "", unreleased.body()));
    sections.stream().filter(r -> !r.version().equals("Unreleased")).forEach(released::add);
    if (released.isEmpty()) throw new IllegalStateException("CHANGELOG.md at " + ref + " has no release");

    // ---- the What's New page
    StringBuilder page = new StringBuilder();
    page.append("---\ntitle: What's New\n");
    // Quoted: a colon and a space in a bare YAML value starts a mapping.
    page.append("description: \"What changed in each release of Termina, newest first: what was added, what works differently and what was fixed.\"\n");
    page.append("category: Help\norder: 14\n---\n\n");
    page.append("<!-- AUTO-GENERATED by scripts/GenChangelog.java from Termina's CHANGELOG.md. Do not edit by hand. -->\n\n");
    page.append("Every release, newest first. The same text is the repository's\n[CHANGELOG.md](").append(blob).append("CHANGELOG.md).\n");
    for (Release r : released) {
        page.append("\n## ").append(r.version());
        if (!r.date().isEmpty()) page.append(" (").append(r.date()).append(')');
        page.append("\n\n").append(repoLinks(r.body().strip(), blob)).append('\n');
    }
    Files.writeString(Path.of("src/content/docs/whats-new.md"), page.toString());

    // ---- the Roadmap page, where the app keeps a TODO.md
    String todo = showOrNull(repo, ref, "TODO.md");
    if (todo != null) {
        StringBuilder road = new StringBuilder();
        road.append("---\ntitle: Roadmap\n");
        road.append("description: \"What Termina does not do yet: the guidelines it has still to meet, what has never been run on each system, and the terminal features not built.\"\n");
        road.append("category: Help\norder: 15\n---\n\n");
        road.append("<!-- AUTO-GENERATED by scripts/GenChangelog.java from Termina's TODO.md. Do not edit by hand. -->\n\n");
        road.append("What is not done yet, as the repository's own\n[TODO.md](").append(blob).append("TODO.md) lists it. An item leaves the list in the change that does it.\n\n");
        // Without the file's own title, which the page already has.
        road.append(repoLinks(todo.replaceFirst("(?s)\\A\\s*# [^\\n]*\\n", "").strip(), blob)).append('\n');
        Files.writeString(Path.of("src/content/docs/roadmap.md"), road.toString());
    }

    // ---- the home page's block
    List<News> news = highlights(released.getFirst(), 6);
    List<News> next = as == null && unreleased != null ? highlights(unreleased, 6) : List.of();
    StringBuilder ts = new StringBuilder();
    ts.append("// AUTO-GENERATED by scripts/GenChangelog.java from Termina's CHANGELOG.md — do not edit by hand.\n");
    ts.append("// The home page's \"What's new\" block: the first entries of the newest release, each one's bold\n");
    ts.append("// summary as its title. `next` is what is in the repository and not in a release yet.\n\n");
    ts.append("export type NewsItem = { title: string; detail: string };\n\n");
    ts.append("export const whatsNew: NewsItem[] = [\n");
    ts.append("  { title: ").append(quote("Termina " + released.getFirst().version())).append(", detail: ")
            .append(quote("Out for macOS (Apple Silicon and Intel), Windows (x64) and Linux (x64 and ARM64), each installer with its own Java runtime."))
            .append(" },\n");
    for (News n : news) ts.append("  { title: ").append(quote(n.title())).append(", detail: ").append(quote(n.detail())).append(" },\n");
    ts.append("];\n\nexport const next: NewsItem[] = [\n");
    for (News n : next) ts.append("  { title: ").append(quote(n.title())).append(", detail: ").append(quote(n.detail())).append(" },\n");
    ts.append("];\n");
    Files.writeString(Path.of("src/lib/whatsnew.ts"), ts.toString());

    System.out.println("whats-new.md: " + released.size() + " releases, newest " + released.getFirst().version()
            + (todo != null ? "; roadmap.md" : "; no TODO.md at " + ref) + "; whatsnew.ts: " + news.size() + " + "
            + next.size() + " (from " + repo + " at " + ref + ")");
}

/** The changelog's sections: "## [0.14.0] - 2026-10-31" and "## [Unreleased]", each with its text. */
static List<Release> sections(String changelog) {
    List<Release> out = new ArrayList<>();
    Matcher m = Pattern.compile("(?m)^## \\[([^\\]]+)\\](?: - (\\S+))?\\s*$").matcher(changelog);
    int bodyStart = -1;
    String version = null;
    String date = "";
    while (m.find()) {
        if (version != null) out.add(new Release(version, date, changelog.substring(bodyStart, m.start())));
        version = m.group(1);
        date = m.group(2) == null ? "" : m.group(2);
        bodyStart = m.end();
    }
    if (version != null) {
        // The link definitions at the foot of the file are not part of the last release.
        String rest = changelog.substring(bodyStart).replaceAll("(?m)^\\[[^\\]]+\\]: \\S+\\s*$", "");
        out.add(new Release(version, date, rest));
    }
    return out;
}

/**
 * A link to a file of the repository, which in the changelog is relative to its root and on the
 * website would resolve under /docs/…: pointed at the file on GitHub. Only a real path (a name
 * with an extension, folders before it), so a placeholder in an example is left alone.
 */
static String repoLinks(String md, String blob) {
    return Pattern.compile("\\]\\(((?:\\.\\./)*(?:[A-Za-z0-9_.-]+/)*[A-Za-z0-9_-][A-Za-z0-9_.-]*\\.[A-Za-z]+(?:#[^)]*)?)\\)")
            .matcher(md)
            .replaceAll(link -> Matcher.quoteReplacement("](" + blob + link.group(1).replaceFirst("^(\\.\\./)+", "") + ")"));
}

/** The first entries of a release that open with a bold summary: the summary, and what follows it. */
static List<News> highlights(Release release, int most) {
    List<News> out = new ArrayList<>();
    Matcher entry = Pattern.compile("(?ms)^- \\*\\*(.+?)\\*\\*(.*?)(?=^- |^### |\\z)").matcher(release.body());
    while (entry.find() && out.size() < most) {
        String summary = entry.group(1).replaceAll("\\s+", " ").strip();
        String title = inline(summary).replaceAll("[.:,]$", "");
        String after = entry.group(2).replaceAll("\\s+", " ");
        // "**Help ▸ Doctor** checks what…": the summary is the sentence's subject, so the detail
        // is the whole sentence. "**A High Contrast theme**: white on black…" stands apart from it.
        boolean subject = after.matches("^ [a-z].*") && !summary.matches(".*[.:,]$");
        String detail = subject ? summary + after : after.strip().replaceFirst("^[.:,]\\s*", "");
        // The first two sentences are enough for a card.
        Matcher two = Pattern.compile("^(.+?[.!?])(\\s+.+?[.!?])?(\\s|$)").matcher(detail);
        if (two.find()) detail = (two.group(1) + (two.group(2) == null ? "" : two.group(2))).strip();
        if (detail.isEmpty()) continue;
        out.add(new News(title, inline(detail.substring(0, 1).toUpperCase(Locale.ROOT) + detail.substring(1))));
    }
    return out;
}

/** Inline Markdown as the home page's HTML: entities escaped, code spans kept, links flattened. */
static String inline(String s) {
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
    s = s.replaceAll("`([^`]+)`", "<code>$1</code>");
    s = s.replaceAll("\\*\\*([^*]+)\\*\\*", "$1");
    s = s.replaceAll("\\[([^\\]]+)\\]\\([^)]+\\)", "$1");
    return s;
}

static String quote(String s) {
    return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
}

static String show(Path repo, String ref, String path) throws IOException, InterruptedException {
    Process p = new ProcessBuilder("git", "-C", repo.toString(), "show", ref + ":" + path).start();
    String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
    String err = new String(p.getErrorStream().readAllBytes(), StandardCharsets.UTF_8);
    if (p.waitFor() != 0) throw new IllegalStateException("git show " + ref + ":" + path + " failed: " + err.strip());
    return out;
}

static String showOrNull(Path repo, String ref, String path) throws IOException, InterruptedException {
    Process p = new ProcessBuilder("git", "-C", repo.toString(), "show", ref + ":" + path)
            .redirectError(ProcessBuilder.Redirect.DISCARD)
            .start();
    String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
    return p.waitFor() == 0 ? out : null;
}

static String newestTag(Path repo) throws IOException, InterruptedException {
    Process p = new ProcessBuilder("git", "-C", repo.toString(), "tag", "--list", "v*", "--sort=-v:refname").start();
    String out = new String(p.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
    p.waitFor();
    return out.lines()
            .filter(t -> t.matches("v\\d+\\.\\d+\\.\\d+"))
            .findFirst()
            .orElseThrow(() -> new IllegalStateException("no release tag in " + repo));
}
